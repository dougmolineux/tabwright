#!/bin/sh
# Builds everything, installs the native host, writes the native messaging manifest, creates the
# config directory (token, config, profile) and registers the MCP server with Claude Code (SPEC 13).
#   scripts/install.sh [--skip-build] [--no-mcp]
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SKIP_BUILD=0
REGISTER_MCP=1
for arg in "$@"; do
  case "$arg" in
    --skip-build) SKIP_BUILD=1 ;;
    --no-mcp) REGISTER_MCP=0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[33mwarning:\033[0m %s\n' "$*" >&2; }

NODE=$(command -v node || true)
[ -n "$NODE" ] || { echo "node is not on PATH. Install Node.js 20 or later." >&2; exit 1; }
NODE_MAJOR=$("$NODE" -p 'process.versions.node.split(".")[0]')
[ "$NODE_MAJOR" -ge 20 ] || { echo "Node.js 20 or later is required (found $("$NODE" -v))." >&2; exit 1; }

case "$(uname)" in
  Darwin)
    CONF="$HOME/Library/Application Support/ClaudeBridge"
    NMH_DIR="$HOME/Library/Application Support/Mozilla/NativeMessagingHosts"
    ;;
  Linux)
    CONF="${XDG_CONFIG_HOME:-$HOME/.config}/claude-bridge"
    NMH_DIR="$HOME/.mozilla/native-messaging-hosts"
    ;;
  *)
    echo "Unsupported OS: $(uname). Windows support is planned (SPEC milestone M7)." >&2
    exit 1
    ;;
esac
LIB="$HOME/.local/share/claude-bridge"

if [ "$SKIP_BUILD" -eq 0 ]; then
  say "Installing dependencies and building"
  (cd "$ROOT" && npm install --no-audit --no-fund && npm run build)
fi
[ -f "$ROOT/host/dist/index.js" ] && [ -f "$ROOT/mcp-server/dist/index.js" ] || { echo "Build output missing; run without --skip-build." >&2; exit 1; }

FM_BIN=""
if [ "$(uname)" = Darwin ] && [ "$(uname -m)" = arm64 ] && command -v swift >/dev/null 2>&1; then
  OS_MAJOR=$(sw_vers -productVersion | cut -d. -f1)
  if [ "$OS_MAJOR" -ge 26 ]; then
    say "Building the on-device model helper (claude-bridge-fm)"
    if (cd "$ROOT/fm-helper" && swift build -c release >/dev/null 2>&1); then
      FM_BIN="$ROOT/fm-helper/.build/release/claude-bridge-fm"
    else
      warn "Couldn't build fm-helper; instruction mode will fall back to rules only when Claude is unavailable."
    fi
  else
    warn "macOS $OS_MAJOR: the on-device fallback needs macOS 26 or later; skipping it."
  fi
fi

say "Installing the native host to $LIB"
mkdir -p "$LIB"
cp "$ROOT/host/dist/index.js" "$LIB/host.js"
cp "$ROOT/mcp-server/dist/index.js" "$LIB/mcp-server.js"
[ -n "$FM_BIN" ] && cp "$FM_BIN" "$LIB/claude-bridge-fm"
cat > "$LIB/claude-bridge-host" <<WRAP
#!/bin/sh
# Started by Firefox (native messaging). Generated by scripts/install.sh.
exec "$NODE" "$LIB/host.js" "\$@"
WRAP
chmod 755 "$LIB/claude-bridge-host"

say "Writing the native messaging manifest"
mkdir -p "$NMH_DIR"
cat > "$NMH_DIR/claude_bridge.json" <<JSON
{
  "name": "claude_bridge",
  "description": "Bridge between Claude Code and Firefox",
  "path": "$LIB/claude-bridge-host",
  "type": "stdio",
  "allowed_extensions": ["claude-bridge@dougmolineux.dev"]
}
JSON

say "Setting up $CONF"
mkdir -p "$CONF"
chmod 700 "$CONF"
if [ ! -s "$CONF/token" ]; then
  (umask 077; "$NODE" -e 'process.stdout.write(require("crypto").randomBytes(32).toString("hex"))' > "$CONF/token")
fi
chmod 600 "$CONF/token"
if [ ! -f "$CONF/config.json" ]; then
  cat > "$CONF/config.json" <<'JSON'
{
  "allowedUploadDirs": ["~/Documents"],
  "maxUploadBytes": 10485760,
  "snapshotCharLimit": 25000,
  "approvalTimeoutSec": 120,
  "draftFreeText": false
}
JSON
fi
if [ ! -f "$CONF/profile.json" ]; then
  (umask 077; cp "$ROOT/scripts/profile.example.json" "$CONF/profile.json")
fi
chmod 600 "$CONF/config.json" "$CONF/profile.json"

if [ "$REGISTER_MCP" -eq 1 ]; then
  if command -v claude >/dev/null 2>&1; then
    say "Registering the MCP server with Claude Code (user scope)"
    claude mcp remove firefox -s user >/dev/null 2>&1 || true
    claude mcp add -s user firefox -- "$NODE" "$ROOT/mcp-server/dist/index.js"
  else
    warn "claude isn't on PATH; register later with: claude mcp add -s user firefox -- $NODE $ROOT/mcp-server/dist/index.js"
  fi
fi

cat <<DONE

Installed. Next:
  1. Load the extension:
       npx web-ext run --source-dir "$ROOT/extension"      (temporary, development)
     or about:debugging -> This Firefox -> Load Temporary Add-on -> extension/manifest.json
     For daily use, sign it as unlisted: npm run ext:sign (needs AMO API keys).
  2. Click the toolbar button, then Connect, then "Allow Claude on <site>" on a page.
  3. Edit your profile in the sidebar (or $CONF/profile.json).
DONE
